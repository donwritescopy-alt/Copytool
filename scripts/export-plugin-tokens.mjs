// Combines src/styles/tokens/{primitives,semantic,effects}.css into build/plugin-tokens.css
// with every var(--x) resolved to its literal value, so the Figma plugin needs no Tailwind or token chain.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const files = ["primitives", "semantic", "effects"].map((n) => `src/styles/tokens/${n}.css`)
const out = join(root, "build/plugin-tokens.css")

const sources = files.map((f) => [f, readFileSync(join(root, f), "utf8").replace(/\/\*[\s\S]*?\*\//g, "")])

// Base values come from top-level :root only; @media/@supports overrides are resolved against them.
const values = new Map()
for (const [, css] of sources) {
  const topLevel = css.replace(/@(media|supports)[^{]*\{\s*:root\s*\{[^}]*\}\s*\}/g, "")
  for (const [, name, value] of topLevel.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) values.set(name, value.trim())
}

function resolve(text, depth = 0) {
  if (depth > 20) throw new Error(`Token reference cycle near: ${text}`)
  if (!text.includes("var(--")) return text
  return resolve(
    text.replace(/var\((--[\w-]+)\)/g, (_, name) => {
      if (!values.has(name)) throw new Error(`Unknown token ${name}`)
      return values.get(name)
    }),
    depth + 1
  )
}

const body = sources
  .map(([file, css]) => `/* ${file} */\n` + resolve(css).replace(/^[ \t]+$/gm, "").replace(/\n{3,}/g, "\n\n").trim())
  .join("\n\n")

if (body.includes("var(")) throw new Error("Unresolved var() left in output")

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, `/* Generated by scripts/export-plugin-tokens.mjs. Do not edit; run \`npm run tokens:export\`. */\n\n${body}\n`)
console.log(`Wrote ${out} (${values.size} tokens)`)
