// Generates plugin-handoff/plugin-ds.css: resolved tokens + base styles + component classes.
// Reuses the token-resolution logic from export-plugin-tokens.mjs.
import { cpSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const tokenFiles = ["primitives", "semantic", "effects"].map((n) => `src/styles/tokens/${n}.css`)
const out = join(root, "plugin-handoff/plugin-ds.css")

// ── 1. Resolve tokens ──────────────────────────────────────────────────────────
const sources = tokenFiles.map((f) => [f, readFileSync(join(root, f), "utf8").replace(/\/\*[\s\S]*?\*\//g, "")])

const values = new Map()
for (const [, css] of sources) {
  const topLevel = css.replace(/@(media|supports)[^{]*\{\s*:root\s*\{[^}]*\}\s*\}/g, "")
  for (const [, name, value] of topLevel.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) values.set(name, value.trim())
}

function resolve(text, depth = 0) {
  if (depth > 20) throw new Error(`Token reference cycle near: ${text}`)
  if (!text.includes("var(--")) return text
  return resolve(
    text.replace(/var\((--[\w-]+)\)/g, (_, name) => {
      if (!values.has(name)) throw new Error(`Unknown token ${name}`)
      return values.get(name)
    }),
    depth + 1
  )
}

// Build the :root block from resolved tokens
const tokenBlock = sources
  .map(([file, css]) => `  /* ${file} */\n` + resolve(css)
    .replace(/:root\s*\{/g, "")
    .replace(/\}\s*$/gm, "")
    .replace(/@(media|supports)[^{]*\{[^}]*\}/g, "") // fallbacks handled separately
    .replace(/^\s*\n/gm, "")
    .trim()
  )
  .join("\n\n")

// Build fallback blocks with resolved values
function extractFallbacks(css) {
  const blocks = []
  const re = /(@(?:supports|media)[^{]*)\{\s*:root\s*\{([^}]*)\}\s*\}/g
  let m
  while ((m = re.exec(css)) !== null) {
    const condition = m[1].trim()
    const vars = resolve(m[2]).trim()
    blocks.push(`${condition} {\n  .ds-root {\n    ${vars.replace(/\n\s*/g, "\n    ")}\n  }\n}`)
  }
  return blocks
}

const fallbacks = sources.flatMap(([, css]) => extractFallbacks(css))

// Verify no unresolved vars in token values
const allResolved = resolve(tokenBlock)
if (allResolved.match(/var\(--(?!card-spacing|spacing)/)) {
  const leftover = allResolved.match(/var\(--[\w-]+\)/g)
  throw new Error(`Unresolved var() in tokens: ${leftover?.join(", ")}`)
}

