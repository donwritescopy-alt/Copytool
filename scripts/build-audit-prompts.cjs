const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const generatedDir = path.join(root, "src/lib/audit/prompts");
const personas = ["zara", "dot", "sam", "marcus", "bex", "leo", "val"];

function writeModule(sourcePath, outputPath, exportName) {
  const source = fs.readFileSync(path.join(root, sourcePath), "utf8");
  const output = `// Generated by scripts/build-audit-prompts.cjs. Edit audit-prompts/*.md instead.\nexport const ${exportName} = ${JSON.stringify(source)};\n`;
  fs.mkdirSync(path.dirname(path.join(root, outputPath)), { recursive: true });
  fs.writeFileSync(path.join(root, outputPath), output, "utf8");
}

writeModule("audit-prompts/system.md", "src/lib/audit/prompts/system.ts", "AUDIT_SYSTEM_PROMPT");

for (const persona of personas) {
  const exportName = `${persona.toUpperCase()}_PROMPT`;
  writeModule(
    `audit-prompts/personas/${persona}.md`,
    `src/lib/audit/prompts/writers/${persona}.ts`,
    exportName,
  );
}

const writerImports = personas
  .map((persona) => {
    const exportName = `${persona.toUpperCase()}_PROMPT`;
    return `import { ${exportName} } from "./writers/${persona}";`;
  })
  .join("\n");
const writerExports = personas
  .map((persona) => `  ${persona.toUpperCase()}_PROMPT,`)
  .join("\n");
const writersIndex = `${writerImports}\n\nexport {\n${writerExports}\n};\n`;
fs.writeFileSync(path.join(generatedDir, "writers.ts"), writersIndex, "utf8");

console.log(`Generated main prompt and ${personas.length} writer prompts from audit-prompts/.`);
